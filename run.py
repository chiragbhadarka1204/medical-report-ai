# ──────────────────────────────────────────────────────────────
# Step 1: Resolve DB password + write .env
# ──────────────────────────────────────────────────────────────
def get_db_password() -> str:
    """Read DB password from .env if already set, otherwise prompt."""
    # Check if .env already has a real password
    if os.path.exists(ENV_FILE):
        with open(ENV_FILE) as f:
            for line in f:
                if line.startswith("DATABASE_URL=") and "YOUR_DB_PASSWORD" not in line:
                    url = line.strip().split("=", 1)[1]
                    # Extract password from URL
                    try:
                        from urllib.parse import urlparse
                        parsed = urlparse(url)
                        if parsed.password and len(parsed.password) > 4:
                            ok(f".env already has DATABASE_URL set.")
                            return parsed.password
                    except Exception:
                        pass

    print("""
    Supabase direct PostgreSQL password needed.
    Find it at: Supabase Dashboard → Project Settings → Database → Database password
    """)
    while True:
        pwd = getpass.getpass("    Enter your Supabase DB password: ").strip()
        if pwd:
            return pwd
        print("    Password cannot be empty. Try again.")


