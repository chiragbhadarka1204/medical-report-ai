# ──────────────────────────────────────────────────────────────
# Step 4: Test BOB API
# ──────────────────────────────────────────────────────────────
def test_bob_api():
    step(4, f"Testing BOB API ({BOB_API_BASE_URL})")
    try:
        import requests as req
        import base64
        raw_key = base64.b64decode(BOB_API_KEY).decode("utf-8")
        r = req.post(
            f"{BOB_API_BASE_URL}/chat/completions",
            json={"model": BOB_MODEL, "messages": [{"role": "user", "content": "Say: OK"}], "max_tokens": 5},
            headers={"Authorization": f"Bearer {raw_key}", "Content-Type": "application/json", "User-Agent": "medical-report-ai/1.0"},
            timeout=15,
        )
        if r.status_code == 200:
            ok(f"BOB API reachable. Model: {BOB_MODEL}")
        else:
            warn(f"BOB API returned HTTP {r.status_code}: {r.text[:200]}")
            warn("AI features will show errors until the API key is valid.")
    except Exception as e:
        warn(f"BOB API not reachable: {e}")
        warn("AI features will show errors. The app will still run.")


